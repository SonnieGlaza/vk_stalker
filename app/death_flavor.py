def killer_label_for_kind(kind: str, *, npc: bool = False) -> str:
    """Человекочитаемое имя убийцы по ключу вида (kind) мутанта/НПС."""
    if npc:
        return NPC_NAME_OPENERS.get(kind, NPC_GENERIC_NAME)
    return MUTANT_NAME_OPENERS.get(kind, kind or "мутант")


def encounter_phrase_for_kind(kind: str, *, npc: bool = False) -> str:
    """Фраза «с/со <Имя>» (творительный падеж) для лога ближнего столкновения."""
    if npc:
        return NPC_NAME_INSTRUMENTAL.get(kind, NPC_GENERIC_INSTRUMENTAL)
    return MUTANT_NAME_INSTRUMENTAL.get(kind, MUTANT_GENERIC_INSTRUMENTAL)


def infer_death_cause(character: Character, *, cause: str | None = None) -> DeathCause:
    if cause in CAUSE_OPENERS:
        return cause  # type: ignore[return-value]
    hunger = int(getattr(character, "hunger", 0) or 0)
    thirst = int(getattr(character, "thirst", 0) or 0)
    radiation = int(getattr(character, "radiation", 0) or 0)
    # Критические выживательные пороги.
    if hunger >= 100 or thirst >= 100 or radiation >= 100:
        scores = {
            "hunger": hunger,
            "thirst": thirst,
            "radiation": radiation,
        }
        best = max(scores, key=lambda k: scores[k])
        if scores[best] >= 100:
            return best  # type: ignore[return-value]
    if radiation >= 80 and radiation >= hunger and radiation >= thirst:
        return "radiation"
    if hunger >= 80 and hunger >= thirst:
        return "hunger"
    if thirst >= 80:
        return "thirst"
    return "unknown"


def _pick(pool: list[str], rng: random.Random) -> str:
    return rng.choice(pool) if pool else ""


def _location_bits(spot: str, rng: random.Random) -> tuple[str, str]:
    atmosphere = _pick(LOCATION_ATMOSPHERE.get(spot, []), rng) or (
        f"сырой воздух «{spot}» и чужой запах гари"
    )
    fall = _pick(LOCATION_FALL.get(spot, []), rng) or (
        f"рухнул на земле «{spot}» — свет погас"
    )
    return atmosphere, fall


def generate_death_story(
    character: Character,
    *,
    where: str | None = None,
    cause: str | None = None,
    home: str | None = None,
    respawn_cost: int = 500,
    max_hp: int | None = None,
    seed: int | None = None,
    killer_name: str | None = None,
) -> str:
    """Случайный сталкерский текст смерти с привязкой к месту и причине."""
    rng = random.Random(seed) if seed is not None else random.Random()
    spot = h(where or character.location or "Зоне")
    death_cause = infer_death_cause(character, cause=cause)
    atmosphere, fall = _location_bits(spot, rng)
    opener = _pick(CAUSE_OPENERS[death_cause], rng)
    wake = _pick(WAKE_LINES, rng)
    loot = _pick(LOOT_LINES, rng)
    home_base = h(home or "базу")
    hp = int(character.health)
    cap = int(max_hp) if max_hp is not None else max(hp, 100)
    name = h(character.nickname)

    cause_tag = {
        "combat": "бой",
        "mutant": "мутант",
        "npc": "НПС",
        "anomaly": "аномалия",
        "hunger": "голод",
        "thirst": "жажда",
        "radiation": "радиация",
        "emission": "Выброс",
        "coop": "кооп-вылазка",
        "unknown": "Зона",
    }.get(death_cause, "Зона")

    lines = [
        f"☠️ {name}, на «{spot}» ({cause_tag})…",
        opener,
    ]
    if killer_name:
        lines.append(f"Добил: {h(killer_name)}.")
    lines += [
        f"Последнее, что помнишь: {atmosphere}. Ты {fall}.",
        "",
        wake,
        f"Братва затащила на «{home_base}». Зона забрала почти всё, но не дожала.",
        "",
        f"HP: {hp}/{cap} · ☢ {int(character.radiation)} · 🍗 {int(character.hunger)} · 💧 {int(character.thirst)}",
        loot,
        f"Спасение на базе — {respawn_cost} RU"
        + (
            f" (у тебя {int(character.money)} RU — медики оформят долг, спишут с заработка)."
            if int(character.money) < respawn_cost
            else "."
        )
        + " Личный хабар не трогают.",
    ]
    return "\n".join(lines)
